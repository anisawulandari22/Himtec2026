class MarketCity {
  final String id;
  final String name;
  final String province;
  final String marketName;

  const MarketCity({
    required this.id,
    required this.name,
    required this.province,
    required this.marketName,
  });
}

class CommodityMarketItem {
  final String id;
  final String name;
  final String category; // 'Pertanian' atau 'Peternakan'
  final int basePrice; // default base price
  final String unit; // 'kg', 'liter', 'ekor'
  final String unitLabel; // 'pohon', 'rumpun', 'ekor', 'lubang tanam'
  final int defaultWeightGrams; // estimasi gram per panen unit
  final int defaultHolesOrHead; // default populasi
  final int defaultCost; // estimasi biaya operasional
  final Map<String, int> cityPrices; // harga per kota
  final Map<String, String> cityTrends; // tren per kota: 'Tren Naik', 'Stabil', 'Tren Turun'
  final Map<String, int> cityChanges; // perubahan nominal hari ini

  const CommodityMarketItem({
    required this.id,
    required this.name,
    required this.category,
    required this.basePrice,
    required this.unit,
    required this.unitLabel,
    required this.defaultWeightGrams,
    required this.defaultHolesOrHead,
    required this.defaultCost,
    required this.cityPrices,
    required this.cityTrends,
    required this.cityChanges,
  });

  int getPriceForCity(String cityId) {
    return cityPrices[cityId] ?? basePrice;
  }

  String getTrendForCity(String cityId) {
    return cityTrends[cityId] ?? 'Stabil';
  }

  int getChangeForCity(String cityId) {
    return cityChanges[cityId] ?? 0;
  }
}

